"""For each version, the rest of its ``sys.stdlib_module_names``: removed or added since, or private."""

_MODULES: FrozenSet[str] = frozenset(entry.name for entry in PLATFORM_ONLY if entry.is_module)
_ATTRIBUTES: Dict[str, Tuple[str, ...]] = {}
for _entry in PLATFORM_ONLY:
    if not _entry.is_module:
        _module, _, _attribute = _entry.name.rpartition(".")
        _ATTRIBUTES[_module] = (*_ATTRIBUTES.get(_module, ()), _attribute)


def platform_only(dotted: str) -> bool:
    """Whether some desktop platform's Python lacks the module or attribute ``dotted``, or its package.

    Importing ``curses.ascii`` runs ``curses``, which Windows lacks, so a
    platform-only module makes every name below it platform-only too.
    """
    parts = dotted.split(".")
    for end in range(1, len(parts) + 1):
        prefix = ".".join(parts[:end])
        if prefix in _MODULES or prefix in NEEDS_TK:
            return True
    module, _, attribute = dotted.rpartition(".")
    return any(fnmatchcase(attribute, pattern) for pattern in _ATTRIBUTES.get(module, ()))


def stdlib_everywhere(top_level: str) -> bool:
    """Whether every supported Python on every desktop platform has the top-level module ``top_level``."""
    return top_level in STDLIB_ON_EVERY_VERSION and not platform_only(top_level)
