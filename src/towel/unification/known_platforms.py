"""The standard library that some platform or some supported Python lacks, as its documentation says.

A helper's host is imported wherever its borrower is, so a host that imports
``msvcrt``, or reads ``os.startfile`` or ``signal.CTRL_C_EVENT``, breaks a
borrower on macOS and Linux that imported fine before. ``sys.stdlib_module_names``
cannot tell: it lists every module of every platform, and only those of the
Python Towel runs on.

``PLATFORM_ONLY`` is read from the Availability notes of the documentation
sources (``Doc/library/*.rst``) of CPython 3.11.15, 3.12.13 and 3.13.7: a
module's ``:platform:`` option and a note of its own, and the note in the
description of each function, class, exception and data item at a module's
top level. An entry lists, for each version whose documentation notes it, the
desktop platforms of Windows, macOS and Linux the note names, and it is here
only where that leaves one out. ``Unix`` and ``POSIX`` name macOS and Linux
(the documentation says a Unix note holds for macOS unless it says
otherwise), and a minimum release (``Linux >= 3.9``) counts as the platform.

Left out, and so never known to be missing:

- what a note restricts only to WebAssembly and mobile platforms
  (``not WASI``, ``not Android, not iOS``). The documentation says those
  notes mean a module "does not work or is not available", and that
  ``subprocess`` and ``socket`` import there;
- an object whose description holds several notes, one per parameter:
  ``subprocess.Popen``, ``os.pidfd_open``;
- a note the running interpreters contradict, which the documentation
  places on Linux or iOS alone and CPython 3.11 to 3.13 has on macOS too:
  ``os.preadv``, ``os.pwritev``, the ``sys`` stack-trampoline functions and
  ``importlib.machinery.AppleFrameworkLoader``;
- availability stated in prose rather than a note, such as the ``os.O_*``
  constants' "only available on Windows", and undocumented private modules
  (``_winapi``, ``nt``).

``NEEDS_TK`` holds ``tkinter``, which its documentation says is available on
"most Unix platforms, including macOS, as well as on Windows", with the
submodules it marks ``:platform: Tk``. ``STDLIB_ON_EVERY_VERSION`` holds the
names ``sys.stdlib_module_names`` gives on every supported version, so a
module one version removed (``distutils``, ``imp``, ``cgi``) or added is
not taken to be there on another.

tests/test_known_platforms.py holds the running interpreter to every entry
that names its platform as lacking it and to the version lists, so a Python
that adds one fails the suite and returns the list for review.
"""

from __future__ import annotations

from dataclasses import dataclass
from fnmatch import fnmatchcase
from typing import Dict, FrozenSet, Mapping, Tuple

DESKTOP_PLATFORMS: FrozenSet[str] = frozenset({"Windows", "macOS", "Linux"})

_LETTERS = {"W": "Windows", "M": "macOS", "L": "Linux"}


@dataclass(frozen=True)
class PlatformOnly:
    """A module, or a module's attribute, that the documentation places on some desktop platforms only."""

    name: str
    """Its dotted name: ``msvcrt``, ``os.startfile``, or a pattern of names such as ``socket.CAN_*``."""
    is_module: bool
    present_on: Mapping[str, FrozenSet[str]]
    """For each version (``"3.11"``) whose documentation notes it, the desktop platforms it names."""
    source: str
    """The documentation file whose note it is, below ``Doc/library``."""


def _entries(
    source: str, present_on: Mapping[str, str], *names: str, is_module: bool
) -> Tuple[PlatformOnly, ...]:
    platforms = {
        version: frozenset(_LETTERS[letter] for letter in letters if letter in _LETTERS)
        for version, letters in present_on.items()
    }
    return tuple(PlatformOnly(name, is_module, platforms, source) for name in names)


def _modules(source: str, present_on: Mapping[str, str], *names: str) -> Tuple[PlatformOnly, ...]:
    return _entries(source, present_on, *names, is_module=True)


def _attributes(
    source: str, present_on: Mapping[str, str], *names: str
) -> Tuple[PlatformOnly, ...]:
    return _entries(source, present_on, *names, is_module=False)


