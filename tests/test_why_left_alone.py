"""The reasons table in docs/WHY_LEFT_ALONE.md is the one every run prints from.

User-perspective audit of 1.949, finding D4 of the documentation report: every
run printed reason codes that only a 22,000-word specification explained. A run
now prints each reason's sentence and remedy from `towel.reason_sentences`; the
page lists every reason with the same words, so a reader who looks a code up
finds what the run said. The table is generated from that module: when a reason
is added or reworded, regenerate it with

    uv run --frozen python tests/test_why_left_alone.py --write
"""

from __future__ import annotations

from pathlib import Path
import re
import sys
from typing import Iterable, List, Mapping, Tuple

from towel.reason_sentences import (
    OTHER_PAIR_REASON,
    PAIR_REASONS,
    PROPOSAL_REASONS,
    UNTYPEABLE_REASONS,
    Explanation,
    explain,
)

ROOT = Path(__file__).resolve().parents[1]
PAGE = ROOT / "docs" / "WHY_LEFT_ALONE.md"
BEGIN = "<!-- BEGIN reason table: generated by tests/test_why_left_alone.py -->"
END = "<!-- END reason table -->"


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _rows(reasons: Iterable[Tuple[str, Explanation]]) -> List[str]:
    return [
        f"| `{code}` | {_cell(explanation.sentence)} | {_cell(explanation.remedy or '')} |"
        for code, explanation in sorted(reasons)
    ]


HEADER = ["| Reason | What it means | What you can do |", "| --- | --- | --- |"]


def reason_table() -> str:
    """The page's tables: pairs compared, then changes checked, every reason in each."""
    pairs: Mapping[str, Explanation] = {
        **{str(reason): text for reason, text in PAIR_REASONS.items()},
        "other": OTHER_PAIR_REASON,
    }
    checked: Mapping[str, Explanation] = {
        **PROPOSAL_REASONS,
        **{str(reason): text for reason, text in UNTYPEABLE_REASONS.items()},
    }
    lines = [
        BEGIN,
        "",
        "### When Towel compares two places",
        "",
        *HEADER,
        *_rows(pairs.items()),
        "",
        "### When Towel checks a change it has made",
        "",
        *HEADER,
        *_rows(checked.items()),
        "",
        END,
    ]
    return "\n".join(lines)


def _on_page(page: str) -> str:
    assert page.count(BEGIN) == 1 and page.count(END) == 1, "the page must hold one table"
    return BEGIN + page.split(BEGIN, 1)[1].split(END, 1)[0] + END


def test_the_page_lists_every_reason_in_the_words_a_run_prints() -> None:
    page = PAGE.read_text(encoding="utf-8")
    assert _on_page(page) == reason_table(), (
        "docs/WHY_LEFT_ALONE.md's reason table is stale; regenerate it with "
        "`uv run --frozen python tests/test_why_left_alone.py --write`"
    )


def test_every_code_a_run_can_print_is_on_the_page() -> None:
    page = PAGE.read_text(encoding="utf-8")
    listed = set(re.findall(r"^\| `([^`]+)` \|", _on_page(page), re.MULTILINE))
    printable = {str(reason) for reason in PAIR_REASONS} | set(PROPOSAL_REASONS)
    printable |= {str(reason) for reason in UNTYPEABLE_REASONS} | {"other"}
    assert listed == printable
    for code in listed:
        assert explain(code).sentence in page


def test_a_stale_table_is_found() -> None:
    table = reason_table()
    reworded = table.replace(PAIR_REASONS[next(iter(PAIR_REASONS))].sentence, "An older sentence.")
    assert _on_page(f"intro\n{reworded}\nafter") != table


def write() -> None:
    page = PAGE.read_text(encoding="utf-8")
    PAGE.write_text(page.replace(_on_page(page), reason_table()), encoding="utf-8")


if __name__ == "__main__":
    if sys.argv[1:] == ["--write"]:
        write()
    else:
        print(reason_table())
